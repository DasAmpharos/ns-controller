"""Generate golden test vectors for procon.c from the Python Controller that worked over the Linux USB gadget.

Feeds OUT reports to ns_controller.controller.Controller through a fake /dev/hidg0 and records the replies.
Needs the gRPC-era ns_controller package (tag archive/presplit-brain), e.g. the ns-shiny-hunter venv:

    ../../ns-shiny-hunter/.venv/bin/python test/gen_vectors.py > test/vectors.h
"""

import queue
import threading
import time

import ns_controller.controller as controller_module
from ns_controller.controller import Controller
from ns_controller.pb.ns_controller_pb2 import Button, ControllerState, Position


class FakeHid:
    """Stands in for the gadget's /dev/hidg0: readinto() yields queued requests, write() is recorded."""

    def __init__(self) -> None:
        self.requests: queue.Queue[bytes] = queue.Queue()
        self.writes: list[bytes] = []
        self.waiting = threading.Event()

    def readinto(self, buf: bytearray) -> int:
        self.waiting.set()
        req = self.requests.get()
        buf[: len(req)] = req
        return len(req)

    def write(self, data: bytes) -> int:
        self.writes.append(bytes(data))
        return len(data)

    def close(self) -> None:
        pass


def subcommand(sub: int, args: bytes = b"") -> bytes:
    # 0x01 report: id, packet counter, 8 bytes rumble, subcommand id, args
    return bytes([0x01, 0x00]) + bytes([0x00, 0x01, 0x40, 0x40, 0x00, 0x01, 0x40, 0x40]) + bytes([sub]) + args


def spi_read(addr: int, length: int) -> bytes:
    return subcommand(0x10, addr.to_bytes(4, "little") + bytes([length]))


REQUESTS: list[tuple[str, bytes]] = [
    ("usb_status", bytes([0x80, 0x01])),
    ("usb_handshake", bytes([0x80, 0x02])),
    ("usb_baud", bytes([0x80, 0x03])),
    ("usb_hid_only", bytes([0x80, 0x04])),
    ("usb_stop_hid", bytes([0x80, 0x05])),
    ("rumble_only", bytes([0x10, 0x00]) + bytes(8)),
    ("sub_pairing", subcommand(0x01, bytes([0x04]))),
    ("sub_device_info", subcommand(0x02)),
    ("sub_report_mode", subcommand(0x03, bytes([0x30]))),
    ("sub_trigger_time", subcommand(0x04)),
    ("sub_shipment", subcommand(0x08, bytes([0x00]))),
    ("sub_mcu_config", subcommand(0x21, bytes([0x21, 0x00, 0x01]))),
    ("sub_player_lights", subcommand(0x30, bytes([0x01]))),
    ("sub_home_light", subcommand(0x38, bytes([0x0F]))),
    ("sub_imu_enable", subcommand(0x40, bytes([0x01]))),
    ("sub_imu_sens", subcommand(0x41, bytes([0x03, 0x00, 0x00, 0x01]))),
    ("sub_vibration", subcommand(0x48, bytes([0x01]))),
    ("spi_serial", spi_read(0x6000, 0x10)),
    ("spi_imu_factory", spi_read(0x6020, 0x18)),
    ("spi_stick_factory", spi_read(0x603D, 0x19)),
    ("spi_colours", spi_read(0x6050, 0x0D)),
    ("spi_imu_offsets", spi_read(0x6080, 0x18)),
    ("spi_stick_params", spi_read(0x6098, 0x12)),
    ("spi_user_stick", spi_read(0x8010, 0x18)),
    ("spi_user_imu", spi_read(0x8028, 0x18)),
]

INPUTS: list[tuple[str, int, tuple[float, float], tuple[float, float]]] = [
    ("neutral", 0, (0.0, 0.0), (0.0, 0.0)),
    *[(f"btn_{name}", 1 << int(value), (0.0, 0.0), (0.0, 0.0)) for name, value in Button.items()],
    ("all_buttons", sum(1 << int(v) for v in Button.values()), (0.0, 0.0), (0.0, 0.0)),
    ("ls_up_right", 0, (1.0, 1.0), (0.0, 0.0)),
    ("ls_down_left", 0, (-1.0, -1.0), (0.0, 0.0)),
    ("rs_mixed", 0, (0.0, 0.0), (0.5, -0.25)),
]

# Python Button enum -> C PROCON_BTN_* macro name.
C_BUTTON = {
    "A": "A", "B": "B", "X": "X", "Y": "Y", "L": "L", "R": "R", "ZL": "ZL", "ZR": "ZR",
    "L_STICK": "LSTICK", "R_STICK": "RSTICK", "PLUS": "PLUS", "MINUS": "MINUS", "HOME": "HOME",
    "CAPTURE": "CAPTURE", "DPAD_UP": "UP", "DPAD_DOWN": "DOWN", "DPAD_LEFT": "LEFT", "DPAD_RIGHT": "RIGHT",
}


def c_bytes(b: bytes) -> str:
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}"


def stick_int(v: float) -> int:
    # Same formula as Controller.get_input_buffer (minus the dead `or 0.0`).
    return int(round((1 + v) * 2047.5))


def main() -> None:
    fake = FakeHid()
    controller_module.open = lambda *_args, **_kwargs: fake  # shadow builtin open() inside the module
    ctl = Controller()
    ctl.connect("/dev/hidg0")
    fake.waiting.wait()
    on_open = [w for w in fake.writes if w[0] != 0x30]

    results = []
    for name, req in REQUESTS:
        fake.writes.clear()
        fake.waiting.clear()
        fake.requests.put(req)
        fake.waiting.wait()  # comm thread came back for the next read: request fully handled
        time.sleep(0.02)
        replies = [w for w in fake.writes if w[0] != 0x30]  # drop periodic input reports
        results.append((name, req, replies))
    ctl.stop_input.set()

    print("// Generated by test/gen_vectors.py from ns_controller/controller.py; do not edit by hand.")
    print("#pragma once")
    print('#include "procon.h"')
    print()
    print("typedef struct { const char *name; uint8_t req[64]; uint8_t req_len; uint8_t n_replies; "
          "uint8_t replies[2][64]; } out_vector_t;")
    print("typedef struct { const char *name; uint32_t buttons; uint16_t lx, ly, rx, ry; uint8_t block[11]; } "
          "in_vector_t;")
    print()
    print("static const uint8_t vec_on_open[][64] = {")
    for w in on_open:
        print(f"    {c_bytes(w)},")
    print("};")
    print()
    print("static const out_vector_t out_vectors[] = {")
    for name, req, replies in results:
        assert len(replies) <= 2, name
        reps = ", ".join(c_bytes(r) for r in replies) or "{0}"
        print(f'    {{"{name}", {c_bytes(req)}, {len(req)}, {len(replies)}, {{{reps}}}}},')
    print("};")
    print()
    print("static const in_vector_t in_vectors[] = {")
    for name, buttons, ls, rs in INPUTS:
        state = ControllerState(buttons=buttons, ls=Position(x=ls[0], y=ls[1]), rs=Position(x=rs[0], y=rs[1]))
        block = Controller(state).get_input_buffer()
        c_btns = " | ".join(
            f"PROCON_BTN_{C_BUTTON[n]}" for n, v in Button.items() if buttons >> int(v) & 1 and n in C_BUTTON
        ) or "0"
        axes = ", ".join(str(stick_int(v)) for v in (*ls, *rs))
        print(f'    {{"{name}", {c_btns}, {axes}, {c_bytes(block)}}},')
    print("};")


if __name__ == "__main__":
    main()
